from fastapi import APIRouter, HTTPException
from typing import List, Optional
from datetime import datetime
import uuid

# Fix relative imports to absolute imports
from models.project import Project, ProjectCreate, ProjectStatus, ProjectUpdate
from models.agent import Agent, AgentRole
from models.deliverable import Deliverable, DeliverableType, CodeFile
from services.orchestrator_service import OrchestratorService
from services.project_service import ProjectService

router = APIRouter()
orchestrator = OrchestratorService()
project_service = ProjectService()

@router.post("/", response_model=Project)
async def create_project(project_create: ProjectCreate):
    """Create a new project and initialize CTO agent"""
    try:
        # Create project
        project = Project(
            id=str(uuid.uuid4()),
            status=ProjectStatus.PLANNING,
            created_at=datetime.now(),
            updated_at=datetime.now(),
            **project_create.dict()
        )
        
        # Plan project and create agents
        planned_project = await orchestrator.plan_project(project)
        
        # Store project
        await project_service.create_project(planned_project)
        
        return planned_project
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to create project: {str(e)}")

@router.get("/", response_model=List[Project])
async def get_projects():
    """Get all projects"""
    return await project_service.get_all_projects()

@router.get("/{project_id}", response_model=Project)
async def get_project(project_id: str):
    """Get a specific project"""
    project = await project_service.get_project(project_id)
    if not project:
        raise HTTPException(status_code=404, detail="Project not found")
    return project

